static float    g_vis_eu_prev, g_vis_ev_prev;    /* 上一帧原始误差 */
static float    g_vis_gate_scale = 1.0f;         /* 瞬态连续缩放因子（1=不限制） */
static float    g_vis_k_override = 0.0f;         /* 手动覆盖 K（GP_PARAM_VIS_K，0=不覆盖） */
