static float    g_yaw_sat_dir = 0.0f;

/** 本帧实际用哪个 K：手动覆盖 > AIM 帧带的 > 默认 7.8（超范围一律退回默认） */
static float vis_k_px_deg(const GimbalCmd_t *cmd)
{
    float k = 0.0f;

    if (g_vis_k_override > 0.0f)
    {
        k = g_vis_k_override;
    }
    else if (cmd->vis_k_x100 != 0u)
    {
        k = (float)cmd->vis_k_x100 / 100.0f;
    }
    if ((k < VIS_K_MIN) || (k > VIS_K_MAX))
    {
        k = VIS_K_PX_DEG;
    }
    return k;
}

static void vis_outer_reset(void)
{
    g_vis_eu = 0.0f;
    g_vis_ev = 0.0f;
    g_vis_yaw_off = 0.0f;
    g_vis_pitch_off = 0.0f;
    g_vis_seen = 0u;
    g_vis_last_ms = 0u;
    g_vis_rate_u = 0.0f;
    g_vis_rate_v = 0.0f;
    g_vis_eu_prev = 0.0f;
    g_vis_ev_prev = 0.0f;
    g_vis_gate_scale = 1.0f;
    g_vis_iv_u = 0.0f;              /* 速度记忆也清零（重锁时"从零起步"）*/
    g_vis_iv_v = 0.0f;
    g_vis_ff_u = 0.0f;              /* 前馈低通也清零 */
}

static void vis_outer_step(const GimbalCmd_t *cmd, uint8_t mode,
                           uint32_t now, float dt, float gyro_z_dps)
{
    /* 本帧的像素尺度：K 越大说明处理分辨率越高，死区/闸门这些"像素单位"的
     * 阈值必须跟着放大，否则换个分辨率它们的物理含义就变了。 */
    const float k  = vis_k_px_deg(cmd);
    const float ks = k / VIS_K_PX_DEG;

    /* ---- 新帧才更新误差（像素 -> 变化率 -> 死区 -> EMA）---- */
    if ((cmd->rx_count != 0u) && (cmd->px_ms != g_vis_last_ms))
    {
        float dtf = (float)(cmd->px_ms - g_vis_last_ms) / 1000.0f;
        if ((dtf < 0.001f) || (dtf > 1.0f))
        {
            dtf = 0.025f;               /* 首帧/异常间隔按 40fps 估 */
        }
        g_vis_last_ms = cmd->px_ms;
        if (cmd->aim_valid)
        {
            float eu = (float)cmd->px_ut - (float)cmd->px_us;
            float ev = (float)cmd->px_vt - (float)cmd->px_vs;
            /* 误差变化率（px/s，一阶滤波）——瞬态闸门判据用 */
            g_vis_rate_u += 0.5f * (((eu - g_vis_eu_prev) / dtf) -
                                    g_vis_rate_u);
            g_vis_rate_v += 0.5f * (((ev - g_vis_ev_prev) / dtf) -
                                    g_vis_rate_v);
            g_vis_eu_prev = eu;
            g_vis_ev_prev = ev;
            if (fabsf(eu) < (VIS_DEADBAND_PX * ks))
            {
                eu = 0.0f;
            }
            if (fabsf(ev) < (VIS_DEADBAND_PX * ks))
            {
                ev = 0.0f;
            }
            if (g_vis_seen == 0u)
            {
                g_vis_eu = eu;      /* 第一帧直接落座（不慢慢爬） */
                g_vis_ev = ev;
                g_vis_seen = 1u;
            }
            else
            {
                g_vis_eu += VIS_EMA * (eu - g_vis_eu);
                g_vis_ev += VIS_EMA * (ev - g_vis_ev);
            }
        }
    }
    /* ---- 冻结判据：无效帧 / 断流 / 太久没新帧 / 非 AIM 模式 ---- */
    if ((mode != GP_MODE_AIM) || (cmd->rx_count == 0u) ||
        (cmd->aim_valid == 0u) ||
        ((now - g_vis_last_ms) > VIS_FREEZE_MS))
    {
        return;             /* 冻住偏置：不积分、不清零 */
    }
    /* ---- 瞬态"连续"缩放（见宏说明）：超限越多压得越狠，没有任何时间窗 ----
     * 旧版是"触发就冻/按 200ms+300ms 的节拍压到 25%"，那是平台"一顿一顿"
     * 的直接来源（环路增益被切成方波）。现在只用瞬时量算比例：
     *   因子 = 1 / (1 + 超限倍数)，两个判据各算一个取小。不超限 = 1.0。*/
    float gate_scale = 1.0f;
    {
        float r_lim = VIS_GATE_PX_S * ks;
        float r_max = fabsf(g_vis_rate_u);
        if (fabsf(g_vis_rate_v) > r_max)
        {
            r_max = fabsf(g_vis_rate_v);
        }
        if (r_max > r_lim)
        {
            gate_scale = r_lim / r_max;         /* 1/(1+倍数) 的等价写法 */
        }
        float g_abs = fabsf(gyro_z_dps);
        if (g_abs > VIS_GATE_DPS)
        {
            float gs = VIS_GATE_DPS / g_abs;
            if (gs < gate_scale)
            {
                gate_scale = gs;
            }
        }
    }
    /* ---- 连续积分出偏置（P + 微分阻尼 + 速度记忆，见宏说明）---- */
    {
        float eu_deg = g_vis_eu / k;               /* 误差换算成"度" */
        float ev_deg = g_vis_ev / k;
        float du_dps = clampf(g_vis_rate_u / k, -200.0f, 200.0f);
        float dv_dps = clampf(g_vis_rate_v / k, -200.0f, 200.0f);
        float du_d = clampf(g_vis_kd_yaw * du_dps,
                            -VIS_D_LIMIT_DPS, VIS_D_LIMIT_DPS);
        float dv_d = clampf(g_vis_kd_pitch * dv_dps,
                            -VIS_D_LIMIT_DPS, VIS_D_LIMIT_DPS);
        /* ---- 速度记忆（II 型环的那层积分，见 VIS_KII_YAW 说明）----
         * 先按"实际作用方向"累积（乘过 VIS_SIGN_*），这样下面 anti-windup 的
         * "是不是还在往限幅方向推"才判断得对。 */
        {
            float ivu = VIS_SIGN_YAW * g_vis_kii_yaw * eu_deg * dt;
            float ivv = VIS_SIGN_PITCH * g_vis_kii_pitch * ev_deg * dt;
            if (!(((g_vis_yaw_off >= g_vis_limyaw_deg) && (ivu > 0.0f)) ||
                  ((g_vis_yaw_off <= -g_vis_limyaw_deg) && (ivu < 0.0f))))
            {
                g_vis_iv_u += ivu;
            }
            if (!(((g_vis_pitch_off >= VIS_LIMIT_PITCH_DEG) && (ivv > 0.0f)) ||
                  ((g_vis_pitch_off <= -VIS_LIMIT_PITCH_DEG) && (ivv < 0.0f))))
            {
                g_vis_iv_v += ivv;
            }
            g_vis_iv_u = clampf(g_vis_iv_u, -VIS_IV_LIM_DPS, VIS_IV_LIM_DPS);
            g_vis_iv_v = clampf(g_vis_iv_v, -VIS_IV_LIM_DPS, VIS_IV_LIM_DPS);
            /* 慢泄漏（τ=4s）：防止"学到一个不再需要的速度"之后一直推着平台走 */
            g_vis_iv_u -= g_vis_iv_u * (dt / VIS_IV_TAU);
            g_vis_iv_v -= g_vis_iv_v * (dt / VIS_IV_TAU);
        }
        /* ---- 目标方位变化率前馈（见 VIS_FF_TAU 说明）----
         * Ḋ = 陀螺 + SIGN·(像素变化率/K)：目标不动时两项自相抵消 -> 0，
         * 所以它只反映"目标（相对世界）真的在动"那部分需求。*/
        {
            float bdot = gyro_z_dps + VIS_SIGN_YAW * (g_vis_rate_u / k);
            float a = dt / (VIS_FF_TAU + dt);
            g_vis_ff_u += a * (bdot - g_vis_ff_u);
        }
        float ru = gate_scale * (VIS_SIGN_YAW * (g_vis_kp_yaw * eu_deg + du_d) +
                                 g_vis_iv_u) +
                   gate_scale * g_vis_ff_sign_yaw * g_vis_ff_gain_yaw * g_vis_ff_u;
        float rv = gate_scale * (VIS_SIGN_PITCH * (g_vis_kp_pitch * ev_deg + dv_d) +
                                 g_vis_iv_v);
        /* ---- 偏航 anti-windup：指令已经顶着限幅时，不许再往同一方向加偏置
         * （反向的修正照收）。没有这一条：平台满舵期间偏置一直涨，
         * 扰动结束后要花好几秒把这些虚账收回来（现场：甩出去又慢慢回正）。*/
        if (((g_yaw_sat_dir > 0.0f) && (ru > 0.0f)) ||
            ((g_yaw_sat_dir < 0.0f) && (ru < 0.0f)))
        {
            ru = 0.0f;
        }
        /* ⚠ 2026-10-14 十四版：限幅改成变量（0x24 在线可改）——快跑/过弯时
         * 需要的偏置速率能到 150°/s 以上，原来写死 120 会在这里悄悄削掉。*/
        ru = clampf(ru, -g_vis_rateyaw_dps, g_vis_rateyaw_dps);
        rv = clampf(rv, -g_vis_ratepitch_dps, g_vis_ratepitch_dps);
        g_vis_yaw_off = clampf(g_vis_yaw_off + ru * dt,
                               -g_vis_limyaw_deg, g_vis_limyaw_deg);
        g_vis_pitch_off = clampf(g_vis_pitch_off + rv * dt,
                                 -VIS_LIMIT_PITCH_DEG, VIS_LIMIT_PITCH_DEG);
    }
}

